class _AdminReturnsViewState extends State<AdminReturnsView> {
  ReturnRequestStatus? _selectedStatus;
  String _query = '';

  AdminWebController get c => widget.controller;

  ReturnRequestStatus? _nextLogicalStatus(ReturnRequestStatus status) =>
      switch (status) {
        ReturnRequestStatus.pending => ReturnRequestStatus.approvedPickup,
        ReturnRequestStatus.approvedPickup => ReturnRequestStatus.inspecting,
        ReturnRequestStatus.inspecting => ReturnRequestStatus.completed,
        _ => null,
      };

  String _nextStepActionLabel(ReturnRequestStatus status) => switch (status) {
        ReturnRequestStatus.pending => 'Duyệt & Điều Shipper',
        ReturnRequestStatus.approvedPickup => 'Kho HN đã nhận & Đổi mới',
        ReturnRequestStatus.inspecting => 'Xác nhận Hoàn tất',
        _ => '',
      };

  List<ReturnRequestModel> _filtered(List<ReturnRequestModel> all) {
    final q = _query.trim().toLowerCase();
    return all.where((r) {
      if (_selectedStatus != null && r.status != _selectedStatus) return false;
      if (q.isEmpty) return true;
      return r.productTitle.toLowerCase().contains(q) ||
          r.customerName.toLowerCase().contains(q) ||
          r.customerPhone.toLowerCase().contains(q) ||
          r.reasonCategory.toLowerCase().contains(q) ||
          r.id.toLowerCase().contains(q);
    }).toList();
  }

  void _openInspectSneaker(ReturnRequestModel req) {
    final matched =
        c.products.firstWhereOrNull((p) => p.id == req.productId) ??
            ProductModel(
              id: req.productId,
              title: req.productTitle,
              stock: 20,
              price: req.refundAmountUsd,
              thumbnail: req.productThumbnail,
              productType: 'ProductType.variable',
              isFeatured: true,
            );
    showAdminProductAndVideoPreviewDialog(
      context,
      controller: c,
      product: matched,
      initialImageUrl: req.imageUrls.isNotEmpty ? req.imageUrls.first : null,
      initialVideoUrl: req.videoUrls.isNotEmpty ? req.videoUrls.first : null,
      customerActionSummary:
          '🔄 Yêu cầu ${req.typeLabel()} (${req.requestedSizeOrColor}) • Lý do: ${req.reasonCategory} — "${req.description}"',
    );
  }

