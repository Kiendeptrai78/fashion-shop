class ShopTranslations extends Translations {
  @override
  Map<String, Map<String, String>> get keys => {'vi': shopVietnamese, 'en': {for (final key in shopVietnamese.keys) key: key}};
}

String shopTranslate(String value, {String language = 'vi'}) {
  if (language != 'vi') return value;
  final exact = shopVietnamese[value];
  if (exact != null) return exact;
  final patterns = <String, String Function(Match)>{
    r'^(\d+) recent reviews$': (m) => '${m[1]} đánh giá gần đây',
    r'^(.+) is required$': (m) => '${shopTranslate(m[1]!)} không được để trống',
    r'^(\d+)% off$': (m) => 'Giảm ${m[1]}%',
    r'^(\d+) products · Page (\d+)$': (m) => '${m[1]} sản phẩm · Trang ${m[2]}',
    r'^Page (\d+)$': (m) => 'Trang ${m[1]}',
    r'^Filters \((\d+)\)$': (m) => 'Bộ lọc (${m[1]})',
    r'^(\d+) items? in your bag$': (m) => '${m[1]} sản phẩm trong giỏ',
    r'^(\d+) saved pairs? · Tap a pair to choose your size$': (m) => '${m[1]} đôi đã lưu · Chạm để chọn kích cỡ',
    r'^Qty (\d+)$': (m) => 'SL ${m[1]}',
    r'^Explore more from the (.+) collection\.$': (m) => 'Khám phá thêm giày ${shopTranslate(m[1]![0].toUpperCase() + m[1]!.substring(1)).toLowerCase()}.',
    r'^(\d+) pairs available in EU (.+)\.$': (m) => 'Còn ${m[1]} đôi kích cỡ EU ${m[2]}.',
    r'^(In Stock|In stock|Out of stock|Out of Stock) · (\d+) pairs$': (m) => '${shopTranslate(m[1]!)} · ${m[2]} đôi',
    r'^(\d+) colors · (.+)$': (m) => '${m[1]} màu · ${shopTranslate(m[2]!)}',
    r'^ADIDAS · (.+)$': (m) => 'ADIDAS · ${shopTranslate(m[1]!)}',
  };
  for (final entry in patterns.entries) {
    final match = RegExp(entry.key).firstMatch(value);
    if (match != null) return entry.value(match);
  }
  if (value.contains(' from the ') && value.contains('Sample catalog:')) {
    final name = value.split(' from the ').first;
    return '$name. Chọn màu sắc yêu thích và kích cỡ EU 38–44. Danh mục mẫu: giá và tồn kho là dữ liệu minh họa.';
  }
  if (value.contains(' · ')) return value.split(' · ').map((part) => shopTranslate(part)).join(' · ');
  if (value.startsWith('Color: ')) return 'Màu: ${shopTranslate(value.substring(7))}';
  if (value.startsWith('Size: ')) return 'Cỡ: ${value.substring(6)}';
  if (value.contains(' / ')) return value.split(' / ').map((part) => shopTranslate(part)).join(' / ');
  return value;
}
